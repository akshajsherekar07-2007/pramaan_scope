import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { once } from 'node:events';
import { createApp } from '../../server/index';

test('protected setup, reviewer and institution accounts complete the correction journey', async ({ page }) => {
  const root = await mkdtemp(join(tmpdir(), 'pramaan-access-ui-'));
  const { app, store } = await createApp(root, { mode: 'pilot' });
  const server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const password = 'abcdef';
  try {
    await mkdir('submission/screenshots', { recursive: true });
    await page.goto(base); await expect(page.getByRole('heading', { name: 'Set up your reviewer account' })).toBeVisible();
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
      await page.screenshot({ path: `submission/screenshots/protected-setup-${width}.png`, fullPage: true });
      const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
      expect(audit.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.failureSummary) }))).toEqual([]);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await expect(page.getByLabel('First-run key', { exact: true })).toHaveCount(0);
    await page.getByLabel('Your name', { exact: true }).fill('Test reviewer');
    await page.getByLabel('Username or email', { exact: true }).fill('reviewer@example.com');
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Create account' }).click();
    await expect(page.getByRole('heading', { name: 'Pragati Institute of Technology' })).toBeVisible();
    await expect(page.getByLabel('Demonstration persona')).toHaveCount(0);
    expect((await page.context().cookies()).filter(cookie => cookie.name.startsWith('pramaan_session_')).every(cookie => cookie.httpOnly && cookie.sameSite === 'Strict')).toBeTruthy();
    expect(await page.evaluate(() => document.cookie)).not.toContain('pramaan_session_');
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Workspace accounts' });
    await expect(dialog.getByText('Test reviewer', { exact: true })).toBeVisible();
    await dialog.getByLabel('Account name', { exact: true }).fill('Test campus office');
    await dialog.getByLabel('New username or email', { exact: true }).fill('campus-office@example.com');
    await dialog.getByLabel('Initial password', { exact: true }).fill(password);
    await dialog.getByRole('button', { name: 'Create institution account', exact: true }).click();
    await expect(dialog.getByText('Institution account created for this application.')).toBeVisible();
    const accountAudit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    expect(accountAudit.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => node.failureSummary) }))).toEqual([]);
    await page.screenshot({ path: 'submission/screenshots/protected-accounts.png', fullPage: true });
    await dialog.getByRole('button', { name: 'Close dialog' }).click();
    await page.getByRole('button', { name: 'Inspect discrepancy', exact: true }).click();
    await page.getByLabel('Review note').fill('PRIVATE BROWSER TEST REVIEW NOTE 915.');
    await page.getByRole('button', { name: 'Mark reviewed', exact: true }).click();
    await page.getByLabel('Review note').fill('Provide evidence covering Campus A.');
    await page.getByRole('button', { name: 'Request clarification', exact: true }).click();
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible();
    await page.getByLabel('Username or email', { exact: true }).fill('campus-office@example.com');
    await page.getByLabel('Password', { exact: true }).fill('invalid');
    await page.getByRole('button', { name: 'Sign in' }).click();
    await expect(page.getByRole('alert')).toHaveText('Username or password is incorrect.');
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Sign in' }).click();
    await expect(page.getByRole('heading', { name: 'Clarifications for your institution' })).toBeVisible();
    await expect(page.getByText('Provide evidence covering Campus A.', { exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Accounts', exact: true })).toHaveCount(0);
    await expect(page.getByRole('link', { name: 'Export report' })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Reset demo', exact: true })).toHaveCount(0);
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Evidence review', exact: false }).click();
    await expect(page.getByText('PRIVATE BROWSER TEST REVIEW NOTE 915.', { exact: true })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Mark reviewed', exact: true })).toBeDisabled();
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Change impact', exact: false }).click();
    await page.getByRole('button', { name: 'Use corrected sample', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Findings requiring reconsideration' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Accept & recalculate', exact: true })).toBeDisabled();
    await page.screenshot({ path: 'submission/screenshots/protected-institution-impact.png', fullPage: true });
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByLabel('Username or email', { exact: true }).fill('reviewer@example.com'); await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Sign in' }).click();
    await expect(page.getByRole('heading', { name: 'Pragati Institute of Technology' })).toBeVisible();
    await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Change impact', exact: false }).click();
    await page.getByRole('button', { name: 'Accept & recalculate', exact: true }).click();
    await expect(page.getByText('Replacement accepted. Affected findings recalculated; earlier reviews retained.')).toBeVisible();
    await page.getByRole('button', { name: 'Accounts', exact: true }).click();
    await page.getByRole('button', { name: 'Disable access', exact: true }).click();
    await expect(page.getByText('campus-office@example.com · Institution · Disabled', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Close dialog' }).click();
    expect(errors).toEqual([]);
  } finally {
    await new Promise<void>(done => server.close(() => done())); store.close();
    const absolute = resolve(root); if (!absolute.startsWith(resolve(tmpdir()) + sep) || !absolute.includes('pramaan-access-ui-')) throw new Error('Unexpected browser-test directory.');
    await rm(absolute, { recursive: true, force: true });
  }
});
